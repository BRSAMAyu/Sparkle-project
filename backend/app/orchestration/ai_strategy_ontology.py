def get_term_definition(term: str) -> StrategyTermDefinition | None:
    return TERM_DEFINITIONS.get(str(term or "").strip())


def get_value_doctrine(term: str, value: Any) -> StrategyValueDoctrine | None:
    definition = get_term_definition(term)
    if definition is None:
        return None
    return definition.get(value)


def governed_terms() -> tuple[str, ...]:
    return tuple(TERM_DEFINITIONS.keys())


def model_facing_terms() -> tuple[str, ...]:
    return tuple(
        term
        for term, definition in TERM_DEFINITIONS.items()
        if definition.exposure_class in {"model_facing", "mixed"} and not definition.internal_only
    )


