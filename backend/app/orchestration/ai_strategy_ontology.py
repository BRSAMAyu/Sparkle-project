from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any


@dataclass(frozen=True)
class StrategyValueDoctrine:
    value: str
    short_label: str
    behavioral_meaning: str
    target_user_effect: str
    positive_instructions: tuple[str, ...]
    negative_instructions: tuple[str, ...]
    response_shape_guidance: tuple[str, ...]
    grounding_tool_implications: tuple[str, ...]
    compatibility_notes: tuple[str, ...] = ()
    model_summary_en: str = ""
    model_summary_zh: str = ""


@dataclass(frozen=True)
class StrategyTermDefinition:
    term: str
    family: str
    exposure_class: str
    runtime_owner: str
    values: dict[str, StrategyValueDoctrine] = field(default_factory=dict)
    internal_only: bool = False
    notes: tuple[str, ...] = ()

    def get(self, value: Any) -> StrategyValueDoctrine | None:
        normalized = str(value or "").strip()
        if not normalized:
            return None
        return self.values.get(normalized)


def _value(
    value: str,
    *,
    short_label: str,
    behavioral_meaning: str,
    target_user_effect: str,
    positive_instructions: tuple[str, ...],
    negative_instructions: tuple[str, ...],
    response_shape_guidance: tuple[str, ...],
    grounding_tool_implications: tuple[str, ...],
    compatibility_notes: tuple[str, ...] = (),
    model_summary_en: str,
    model_summary_zh: str,
) -> StrategyValueDoctrine:
    return StrategyValueDoctrine(
        value=value,
        short_label=short_label,
        behavioral_meaning=behavioral_meaning,
        target_user_effect=target_user_effect,
        positive_instructions=positive_instructions,
        negative_instructions=negative_instructions,
        response_shape_guidance=response_shape_guidance,
        grounding_tool_implications=grounding_tool_implications,
        compatibility_notes=compatibility_notes,
        model_summary_en=model_summary_en,
        model_summary_zh=model_summary_zh,
    )


